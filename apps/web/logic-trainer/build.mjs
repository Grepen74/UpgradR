// Builds the static logic test trainer into apps/web/public/logic-trainer/, which Vite copies
// verbatim into dist/client so the Worker serves it at /logic-trainer/.
//
// The output is committed. Run `npm run build:logic-trainer --workspace @upgradr/web` after editing
// any source file here; trainer.test.ts fails if the committed output is out of date.
//
// Everything runs in the browser, so no Worker CPU is used. The page loads its script and styles
// as same-origin files because the site's Content-Security-Policy (worker/security.ts) forbids
// inline <script>/<style> and style="" attributes.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const sourceDir = dirname(fileURLToPath(import.meta.url));
export const outputDir = join(sourceDir, "..", "public", "logic-trainer");

const GENERATED = "Generated by apps/web/logic-trainer/build.mjs. Do not edit; edit the sources and rebuild.";

/** Returns the built files as { fileName: contents }. */
export function buildFiles() {
  const read = (name) => readFileSync(join(sourceDir, name), "utf8");
  const bank = JSON.stringify(JSON.parse(read("bank.json")));
  return {
    "index.html": read("index.html").replace("<head>", `<head>\n<!-- ${GENERATED} -->`),
    "styles.css": `/* ${GENERATED} */\n${read("styles.css")}`,
    "trainer.js": `// ${GENERATED}\nconst DATA = ${bank};\n${read("engine.js")}\n${read("app.js")}`,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(outputDir, { recursive: true });
  for (const [name, contents] of Object.entries(buildFiles())) {
    writeFileSync(join(outputDir, name), contents);
  }
  console.log(`Built logic trainer into ${outputDir}`);
}
